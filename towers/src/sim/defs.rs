/// Damage multiplier in percent [DamageClass][ArmorClass]
pub const DMG_MATRIX: [[i32; 4]; 6] = [
    // Light, Armored, Fortified, Flying
    [120, 90, 75, 115],  // Kinetic
    [110, 115, 85, 105], // Arcane
    [135, 85, 100, 95],  // Fire
    [75, 125, 145, 50],  // Siege
    [100, 100, 95, 125], // Flux
    [100, 125, 110, 100], // Void
];

#[inline]
pub fn calc_damage(raw_dmg: i32, dmg_class: DamageClass, armor_class: ArmorClass, armor: i32) -> i32 {
    let mult = DMG_MATRIX[dmg_class as usize][armor_class as usize];
    let scaled = (raw_dmg * mult) / 100;
    let reduced = scaled - armor.max(0);
    reduced.max(2)
}

