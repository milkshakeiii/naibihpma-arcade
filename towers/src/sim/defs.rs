#[inline]
pub fn building_def(kind: BuildingType) -> &'static BuildingDef {
    &BUILDING_DEFS[kind.index()]
}

#[inline]
pub fn unit_def(kind: UnitKind) -> &'static UnitDef {
    &UNIT_DEFS[kind.index()]
}

#[inline]
pub fn building_cost(kind: BuildingType, team: FactionTeam) -> i32 {
    let base = building_def(kind).cost;
    (base * team.cost_pct() + 50) / 100
}

#[inline]
pub fn upgrade_cost(kind: BuildingType, team: FactionTeam) -> i32 {
    let c = building_cost(kind, team);
    (c * 65 + 50) / 100
}
