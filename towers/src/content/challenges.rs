pub fn create_challenge_state(def: &ChallengeDef, seed: u64) -> GameState {
    let maps = build_maps();
    let map = &maps[def.map_id];
    let mut state = GameState::new_empty(
        seed,
        map.tiles,
        FactionTeam::one(def.faction),
        FactionTeam::one(def.p2_faction),
        def.p1_res,
        def.p2_res,
        Some(def.goal),
    );
    if let Some((x, y)) = def.p1_citadel {
        state.spawn_building_raw(TeamId::P1, BuildingType::Citadel, x, y, true);
    }
    if let Some((x, y)) = def.p2_citadel {
        state.spawn_building_raw(TeamId::P2, BuildingType::Citadel, x, y, true);
    }
    for p in def.preplaced {
        state.spawn_building_raw(p.owner, p.kind, p.x, p.y, true);
    }
    state.refresh_caches();
    state
}

pub fn step_challenge_waves(def: &ChallengeDef, state: &mut GameState) {
    if state.outcome != MatchOutcome::Ongoing {
        return;
    }
    for w in def.waves {
        if state.tick >= w.tick && (state.tick - w.tick) % w.repeat_every == 0 {
            for k in 0..w.count {
                let oy = (w.y as i32 + (k as i32 - 1).clamp(-1, 1)).clamp(0, MAP_H as i32 - 1) as u8;
                state.spawn_unit_raw(TeamId::P2, w.kind, w.x, oy);
            }
        }
    }
}
