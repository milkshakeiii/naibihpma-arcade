#[derive(Clone, Copy, Debug)]
pub struct PreplacedBuilding {
    pub owner: TeamId,
    pub kind: BuildingType,
    pub x: u8,
    pub y: u8,
}

#[derive(Clone, Copy, Debug)]
pub struct ScriptWave {
    pub tick: u32,
    pub repeat_every: u32,
    pub kind: UnitKind,
    pub x: u8,
    pub y: u8,
    pub count: u8,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LessonTrigger {
    HasBuilding(BuildingType, usize),
    HasLeyLinks(usize),
    HasGizmoBuff,
    HasWalkerAtMinX(u8),
    HasRaisedStone,
    EnemyStructuresLeftMax(usize),
}

impl LessonTrigger {
    pub fn is_met(self, state: &GameState) -> bool {
        match self {
            LessonTrigger::HasBuilding(kind, min_count) => {
                state
                    .buildings
                    .iter()
                    .filter(|b| b.hp > 0 && b.owner == TeamId::P1 && b.build_ticks_left == 0 && b.kind == kind)
                    .count()
                    >= min_count
            }
            LessonTrigger::HasLeyLinks(min_links) => {
                state
                    .energy_grid
                    .ley_links
                    .iter()
                    .filter(|l| l.owner == TeamId::P1)
                    .count()
                    >= min_links
            }
            LessonTrigger::HasGizmoBuff => state
                .buildings
                .iter()
                .any(|b| b.hp > 0 && b.owner == TeamId::P1 && b.gizmo_buff),
            LessonTrigger::HasWalkerAtMinX(min_x) => state
                .buildings
                .iter()
                .any(|b| b.hp > 0 && b.owner == TeamId::P1 && b.kind.is_walker() && b.x >= min_x),
            LessonTrigger::HasRaisedStone => state.terrain.iter().any(|&t| t == Terrain::RaisedStone),
            LessonTrigger::EnemyStructuresLeftMax(max_left) => {
                state
                    .buildings
                    .iter()
                    .filter(|b| b.hp > 0 && b.owner == TeamId::P2)
                    .count()
                    <= max_left
            }
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct LessonStep {
    pub title: &'static str,
    pub body: &'static str,
    pub action_hint: &'static str,
    pub icon_mask: EnergyMask,
    pub highlight_tile: Option<(u8, u8)>,
    pub highlight_card: Option<usize>,
    pub trigger: LessonTrigger,
}

#[derive(Clone, Copy, Debug)]
pub struct ChallengeDef {
    pub id: usize, // 0..34
    pub faction: Faction,
    pub tier: u8, // 0..4 (0 = Explanation Level)
    pub title: &'static str,
    pub goal_label: &'static str,
    pub briefing_1: &'static str,
    pub briefing_2: &'static str,
    pub tip: &'static str,
    pub goal: ChallengeGoal,
    pub par_ticks: u32,
    pub map_id: usize,
    pub p1_res: i32,
    pub p2_res: i32,
    pub p2_faction: Faction,
    pub p1_citadel: Option<(u8, u8)>,
    pub p2_citadel: Option<(u8, u8)>,
    pub uses_ai: bool,
    pub preplaced: &'static [PreplacedBuilding],
    pub waves: &'static [ScriptWave],
    pub lesson_steps: &'static [LessonStep],
}

